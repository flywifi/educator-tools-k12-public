#!/usr/bin/env bash
# Publish the built ChatGPT/Codex and Antigravity packs as the root of the orphan branch
# `teacher-packs`, the git source that .agents/plugins/marketplace.json on main points Codex and
# the ChatGPT desktop app at. Generated output: one force-pushed commit per release, never edited
# by hand. Usage: tools/publish_teacher_packs.sh <remote-url> <tag>   (run from the repo root,
# after `python3 tools/build_teacher_pack.py --zip`)
set -euo pipefail
remote="$1"; tag="$2"
src="$(pwd)/dist/teacher-packs"
for d in chatgpt-plugin antigravity; do
  [ -f "$src/$d/plugin.json" ] || { echo "publish_teacher_packs: missing $src/$d/plugin.json" >&2; exit 1; }
done
work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT
cp -R "$src/chatgpt-plugin" "$src/antigravity" "$work/"
cat > "$work/README.md" <<EOF
# Teacher Operating System — teacher packs (${tag})

Generated by .github/workflows/frozen-build.yml at each release from main. Do not edit here.

- chatgpt-plugin/ — the ChatGPT desktop / Codex plugin (marketplace: .agents/plugins/marketplace.json on main)
- antigravity/ — the Antigravity plugin (or install the release zip with /plugin or agy plugin install)
EOF
git -C "$work" init -q -b teacher-packs
git -C "$work" add -A
git -C "$work" -c user.name="github-actions[bot]" \
  -c user.email="41898282+github-actions[bot]@users.noreply.github.com" commit -q -m "teacher packs ${tag}"
git -C "$work" push -q -f "$remote" teacher-packs
echo "publish_teacher_packs: teacher-packs now holds ${tag}"
